import {launch, sleep, toI16, clicks} from '../h.mjs';
import fs from 'fs';
const br = await launch(); const ctx = await br.newContext(); const p = await ctx.newPage(); const errs = [];
p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await p.setContent(fs.readFileSync(new URL('../../../../snapshots/', import.meta.url).pathname + 'G9STAGE.html', 'utf8'));
await p.waitForFunction(() => window.SYNQUENZER && SYNQUENZER.version, null, {timeout: 30000}); await sleep(500);
console.log('baseURI', await p.evaluate(() => document.baseURI));
await p.evaluate(() => { SYNQUENZER.newProject(); SYNQUENZER.setBpm(120); }); await sleep(300);
const T = Array.from({length: 8}, (_, k) => .3 + k * .3);
const r = await p.evaluate(([pcm]) => SYNQUENZER.tkInject({pcm, sr: 48000, scene: 0, len: 2}), [toI16(clicks(T, 4))]);
console.log('inject', JSON.stringify(r));
const mk = await p.evaluate(id => SYNQUENZER.wpDetect(id), r.id).catch(e => 'ERR ' + e.message);
console.log('marks', Array.isArray(mk) ? mk.length : mk);
const on = await p.evaluate(ref => { try { return SYNQUENZER.g9Text(ref, true); } catch (e) { return 'THROW ' + e.message; } }, {t: r.track, s: 0});
console.log('g9Text', on);
console.log('sylLoad', await p.evaluate(() => { try { return SYNQUENZER.g9SylLoad('de').then(x => x, e => 'REJECT ' + e.message); } catch (e) { return 'SYNC THROW ' + e.message; } }));
console.log('ed', await p.evaluate(() => ({ed: !!WP.ed, g9: !!(WP.ed && WP.ed.g9), sheet: EL.wpSheet.className})));
const st = await p.evaluate(id => { try { return SYNQUENZER.g9SetAsync(id, {op: 'text', text: 'Gedanken sind frei', lang: 'de'}).then(x => JSON.stringify(x), e => 'REJECT ' + e.message); } catch (e) { return 'SYNC ' + e.message; } }, r.id);
console.log('g9SetAsync', st);
console.log('errs', errs.slice(0, 5).join(' | '));
await br.close();
