// QA musiker run 2: a real sung take via the (fake) microphone with ● REC, then overdub, ↶, playback – which history events?
import {chromium} from 'playwright';
import {writeWav, tone, concat, sleep} from './v3-qa-vs3-h.mjs';
const APP = '/home/user/Synquenzer/bau/helfer/VIDSTAGE/index.html';
const DIR = '/home/user/Synquenzer/bau/helfer/VIDSTAGE/tests/out/mu2';
const SR = 48000, wav = DIR + '/voc.wav';
writeWav(wav, concat(tone(330, 8, SR), tone(550, 8, SR)), SR);
const br = await chromium.launch({args: ['--autoplay-policy=no-user-gesture-required', '--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream', '--use-file-for-fake-audio-capture=' + wav]});
const ctx = await br.newContext({viewport: {width: 390, height: 844}, hasTouch: true, isMobile: true});
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(String(e))); p.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await p.goto('file://' + APP); await p.waitForFunction(() => window.SYNQUENZER && SYNQUENZER.version); await sleep(1500);
const E = (f, a) => p.evaluate(f, a);
await E(r => { SYNQUENZER.play(); SYNQUENZER.stop(); return SYNQUENZER.stimmeStart({route: r, cal: false}); }, 'wired');
await p.waitForFunction(() => SYNQUENZER.stimme().phase === 'live' && SYNQUENZER.vsClock().ring && SYNQUENZER.vsClock().ring.end > 0, null, {timeout: 10000});
await E(() => { SYNQUENZER.setBpm(120); SYNQUENZER.setMetronome(false); SYNQUENZER.setRecOptions({countIn: 0, length: 2}); SYNQUENZER.selectSlot(0, 2); });
await sleep(3000); await E(() => histDrainNow());
let n0 = await E(() => HIST.cur.strs.length);
const waitBeat = b => p.waitForFunction(b => { const c = SYNQUENZER.vsClock(); return c.playing && (c.now - c.outLat - c.start) / c.spb >= b; }, b, {timeout: 60000, polling: 20});
const idle = () => p.waitForFunction(() => !SYNQUENZER.vsInfo().busy && !SYNQUENZER.tkInfo().pend.length && SYNQUENZER.tkInfo().writes === 0, null, {timeout: 30000});
const evs = async () => { await sleep(2800); await E(() => histDrainNow()); const r = await E(n => HIST.cur.strs.slice(n).map(s => JSON.parse(s)), n0); n0 += r.length; return r; };
const show = (name, L) => { console.log('## ' + name); for (const e of L) console.log('   ', e.u, e.u === 'ctx' ? e.z.c : JSON.stringify(e.z.p), JSON.stringify(e.l), 'd' + (e.d || []).length, (e.d || []).map(o => o.op + ' ' + o.path + (o.value && o.value.audio ? ' audio:' + JSON.stringify(o.value.audio).slice(0, 80) : '')).slice(0, 5).join(' ; ')); };
await E(() => SYNQUENZER.play()); await waitBeat(3.5);
await E(() => SYNQUENZER.rec()); await waitBeat(12.8); await idle();
const st = await E(() => SYNQUENZER.tkInfo().stimme);
const c1 = await E(t => SYNQUENZER.getClip(t, 2), st);
console.log('take clip', JSON.stringify(c1 && c1.audio).slice(0, 200));
show('● REC Gesang (2 Takte)', await evs());
// overdub
await E(() => SYNQUENZER.selectSlot(0, 2));
const b0 = await E(() => { const c = SYNQUENZER.vsClock(); return (c.now - c.outLat - c.start) / c.spb; }); const nb = Math.ceil((b0 + 1) / 4) * 4;
await waitBeat(nb - .6); await E(() => SYNQUENZER.rec()); await waitBeat(nb + 8.8); await idle();
show('● REC zweiter Take (Overdub)', await evs());
await E(() => SYNQUENZER.stop());
show('■', await evs());
await sleep(3000);
await E(() => SYNQUENZER.undo());
show('↶ (zweiter Take weg)', await evs());
console.log('check', await E(() => historyCheck({detail: true})), JSON.stringify(await E(() => SYNQUENZER.history())), 'errs', errs.slice(0, 3));
await br.close();
