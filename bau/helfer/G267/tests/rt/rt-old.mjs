// RETEST Alt-Projekt: Projekt + Take in der Basis-App 4.23.0 (vs-base-B.html) anlegen, als ZIP (Projekt + WAV) holen,
// in der G267-Kopie öffnen → Projekt-JSON unverändert (keine neuen Felder), gespielt = Roh-Take bitgleich, auch nach Abspielen.
import {launch, sleep, toI16, deq} from './h.mjs';
import {open} from '../g1/v3-qa-vs3-h.mjs';
import {singer} from './sig.mjs';
import fs from 'fs';
const OUT = []; let fail = 0; const ok = (c, m) => { const s = (c ? '✓ ' : '✗ ') + m; console.log(s); OUT.push(s); if (!c) fail++; };
const hz = m => 440 * Math.pow(2, (m - 69) / 12);
const x = singer(48000, 3, [{t0: 0.1, cons: 's', vib: 15, segs: [{m: 60, d: 0.6, vowel: 'a', f0: hz(60.3)}, {m: 64, d: 0.6, vowel: 'e', f0: hz(63.6)}]}, {t0: 1.6, cons: 't', segs: [{m: 67, d: 0.8, vowel: 'o', f0: hz(67.4)}]}], {seed: 3}).x;
const br = await launch(null);
const A = await open(br, {url: 'file:///home/user/Synquenzer/bau/werkzeug/vs-base-B.html'}), pa = A.p;
const vA = await pa.evaluate(() => SYNQUENZER.version);
await pa.evaluate(() => { SYNQUENZER.newProject(); SYNQUENZER.setBpm(110); SYNQUENZER.setMetronome(false); SYNQUENZER.play(); SYNQUENZER.stop(); });
const rA = await pa.evaluate(pcm => SYNQUENZER.tkInject({pcm, sr: 48000, scene: 0, len: 2}), toI16(x)); await sleep(500);
await pa.evaluate(() => { SYNQUENZER.setClip(0, 0, {len: 2, notes: [{t: 0, d: 2, n: 60, v: .7}, {t: 2, d: 2, n: 65, v: .7}]}); });
const zip = await pa.evaluate(() => SYNQUENZER.tkZipBytes());
const jsonA = await pa.evaluate(() => JSON.parse(SYNQUENZER.serialize()).project);
const rawA = await pa.evaluate(id => SYNQUENZER.tkBufRange(id), rA.id);
await A.ctx.close();
const B = await open(br, {url: 'file:///home/user/Synquenzer/bau/helfer/G267/tests/rt/' + (process.env.G_FILE || 'index.html')}), pb = B.p, errs = [];
pb.on('pageerror', e => errs.push(String(e)));
const vB = await pb.evaluate(() => SYNQUENZER.version);
await pb.evaluate(() => SYNQUENZER.newProject());
const im = await pb.evaluate(z => SYNQUENZER.tkImportZip(z), zip); await sleep(1500);
await pb.evaluate(() => SYNQUENZER.tkLoadAll());
const strip = o => { const c = JSON.parse(JSON.stringify(o)); delete c.saved; delete c.id; delete c.name; return c; };
const jsonB = await pb.evaluate(() => JSON.parse(SYNQUENZER.serialize()).project);
const diffKeys = (a, b, path = '') => { const out = []; if (a && b && typeof a === 'object' && typeof b === 'object') { for (const k of new Set([...Object.keys(a), ...Object.keys(b)])) out.push(...diffKeys(a[k], b[k], path + '.' + k)); } else if (JSON.stringify(a) !== JSON.stringify(b)) out.push(path); return out; };
const d1 = diffKeys(strip(jsonA), strip(jsonB));
ok(im.ok && !d1.length, `Alt-Projekt ${vA} → ${vB} (ZIP mit Take) geöffnet: Projekt-JSON gleich (Unterschiede: ${d1.slice(0, 8).join(' ') || 'keine'})`);
const st = await pb.evaluate(() => SYNQUENZER.tkInfo().stimme);
const id = Object.keys(jsonB.takes || {})[0] || rA.id;
await pb.evaluate(() => { SYNQUENZER.launchScene(0); SYNQUENZER.play(); }); await sleep(5000); await pb.evaluate(() => SYNQUENZER.stop());
const P = await pb.evaluate(([t]) => SYNQUENZER.g2Played({t, s: 0}), [st]);
let d = 0; for (let i = 0; i < rawA.length; i++) if (P.data[i] !== rawA[i]) d++;
ok(P.raw && P.n === rawA.length && d === 0, `Alt-Take nach 5 s Abspielen in ${vB}: gespielt = Roh-Take der Basis-App bitgleich (${d} Samples anders, ${P.n} = ${rawA.length})`);
const jsonC = await pb.evaluate(() => JSON.parse(SYNQUENZER.serialize()).project), d2 = diffKeys(strip(jsonA), strip(jsonC));
ok(!d2.length, `nach dem Abspielen + Speichern: Projekt-JSON weiterhin ohne neue Felder (Unterschiede: ${d2.slice(0, 8).join(' ') || 'keine'})`);
ok(!errs.length, 'keine Seitenfehler ' + errs.join(' | '));
await br.close();
fs.writeFileSync('/home/user/Synquenzer/bau/helfer/G267/tests/rt/out/rt-old.out', OUT.join('\n') + '\n');
console.log(fail ? fail + ' FEHLER' : 'ALLE GRÜN'); process.exit(fail ? 1 : 0);
