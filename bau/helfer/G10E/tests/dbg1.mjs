import {launch, open, take, sleep, pinch, geom, info, openEd} from './h.mjs';
const br = await launch(); const H = await open(br), p = H.p, c = H.cdp;
const {id, ref} = await take(p, [0.5, 1, 1.5, 2]); await openEd(p, ref, id);
await p.evaluate(() => { window.__ev = []; for (const t of ['pointerdown','pointermove','pointerup','pointercancel']) document.addEventListener(t, e => window.__ev.push(t + ' ' + e.pointerId + ' ' + e.target.tagName + ' ' + Math.round(e.clientX)), true); });
const g = await geom(p);
await pinch(c, g.x + g.w * .6, g.y + 90, 60, 240, 4);
await sleep(100);
console.log(await p.evaluate(() => window.__ev.join('\n')));
console.log(await info(p));
await br.close();
