// KON 3: Speichern/Laden (Block + Ursprung bleiben, Zurückholen nach dem Laden exakt), alte Songs laden unverändert
import { open, buildSong, ok, summary, diff, state, OLD } from './lib.mjs';
const {b, ctx, p, errs} = await open();
await buildSong(p);
const s0 = await state(p);
await p.evaluate(() => { SYNQUENZER.blockMake(2, 9); SYNQUENZER.konsolidieren(2, 9, 'Kern'); SYNQUENZER.blockMake(10, 11, 'Schluss'); });
const s1 = await state(p);
ok(s1.song.blocks.length === 2 && s1.song.kons.length === 1, 'Song mit 2 Blöcken und 1 Ursprung');
console.log('Rundreise serialize → normalize');
const rt = await p.evaluate(() => { const o = normalizeProject(JSON.parse(serializeProject())); return JSON.parse(JSON.stringify({song: o.song, parts: o.parts})); });
let d = diff(s1, rt);
ok(d.length === 0, 'Speichern → Laden deep-equal (Song, Teile)', d.slice(0, 5));
const rt2 = await p.evaluate(() => { const o = normalizeProject(JSON.parse(JSON.stringify(normalizeProject(JSON.parse(serializeProject()))))); return JSON.parse(JSON.stringify({song: o.song, parts: o.parts})); });
ok(JSON.stringify(rt) === JSON.stringify(rt2), 'Laden ist stabil (zweimal = gleich)');
console.log('Speichern, Seite neu laden');
const name = await p.evaluate(async () => { const r = SYNQUENZER.save(); if (r && r.then) await r; return S.name; });
await p.waitForTimeout(800);
await p.reload(); await p.waitForTimeout(1800);
const s2 = await state(p);
d = diff(s1, s2);
ok(d.length === 0, 'nach Neuladen: Blöcke, Ursprung, Teil wieder da', d.slice(0, 5));
ok(await p.evaluate(() => { const m = S.song.kons[0].mark; return SYNQUENZER.zurueckholen(m); }), 'Zurückholen nach dem Laden');
const s3 = await state(p);
d = diff({...s0.song, blocks: s3.song.blocks}, s3.song).concat(diff(s0.parts, s3.parts));
ok(d.length === 0, 'exakt Ursprung (nur die Blöcke bleiben)', d.slice(0, 5));
await b.close();

console.log('Alte Songs (R-4261) laden unverändert');
const o = await open({app: OLD});
await buildSong(o.p);
await o.p.evaluate(() => { SYNQUENZER.songRange('asPart', 2, 5, {name: 'Strophe'}); SYNQUENZER.markAction(S.song.marks.find(m => m.a === 6).id, 'rep', 2); SYNQUENZER.sumRange(0, 1, 'Anfang'); });
const old = await o.p.evaluate(() => { const str = serializeProject(), n = normalizeProject(JSON.parse(str)); return {str, norm: JSON.stringify({song: n.song, parts: n.parts, tracks: n.tracks.length}), save: serializeProject.length}; });
ok(o.errs.length === 0, 'alte App ohne Fehler', o.errs);
await o.b.close();
const n = await open();
const neu = await n.p.evaluate(str => { const x = normalizeProject(JSON.parse(str)); return JSON.stringify({song: x.song, parts: x.parts, tracks: x.tracks.length}); }, old.str);
ok(neu === old.norm, 'gleiches Ergebnis wie in R-4261 (JSON byte-gleich)', neu === old.norm ? '' : diff(JSON.parse(old.norm), JSON.parse(neu)).slice(0, 5));
ok(!/"blocks"|"kons"|"sxp"/.test(neu), 'keine neuen Felder in einem alten Song');
const play = await n.p.evaluate(str => { S = normalizeProject(JSON.parse(str)); try { SYNQUENZER.songRange('copy', 0, 1); undo(); } catch (e) { return String(e); } return 'ok'; }, old.str).catch(e => String(e));
ok(play === 'ok', 'alter Song lässt sich bearbeiten', play);
ok(errs.length === 0 && n.errs.length === 0, 'keine Konsolenfehler', errs.concat(n.errs));
await n.b.close();
process.exit(summary('KON-Speichern') ? 1 : 0);
