const L1 = await bassLog(); console.log('bass T8–9 after Synth 3 own clip', L1.join(' '));
check('bass T8–9 sound unchanged by a new own clip on Synth 3', JSON.stringify(L1) === JSON.stringify(L0), {L0, L1});
