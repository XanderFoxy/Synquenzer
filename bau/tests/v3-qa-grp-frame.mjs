// QA group: Claude-viewer-like sandboxed iframe (no same-origin → storage throws, no mic): FANG TEIL → ＋ Song, ▶ SONG, part tap, MIDI/file export
import {chromium} from 'playwright';
import {EXE, check, done} from './v3-qa-grp-lib.mjs';
const sleep = ms => new Promise(r => setTimeout(r, ms));
const D = '/tmp/claude-0/-home-user-Deutsch-Mit-Xander/9f6e2ea9-5438-5564-bb39-64bc754f0143/scratchpad/dirigent-test/';
const br = await chromium.launch({executablePath: EXE, args: ['--autoplay-policy=no-user-gesture-required']});
const pg = await (await br.newContext({viewport: {width: 390, height: 844}, hasTouch: true, isMobile: true})).newPage();
const errs = []; pg.on('pageerror', e => errs.push(String(e))); pg.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
await pg.goto('file://' + D + 'v3-qa-vs2reg/frame-new.html'); await sleep(2500);
const fr = pg.frames().find(f => f !== pg.mainFrame());
await fr.waitForFunction(() => window.SYNQUENZER && window.SYNQUENZER.version, null, {timeout: 20000});
const E = (f, a) => fr.evaluate(f, a);
console.log('in frame', JSON.stringify(await E(() => ({v: SYNQUENZER.version, storage: SYNQUENZER.storage().mode, mic: !!document.querySelector('#segMic') && getComputedStyle(document.querySelector('#segMic')).display, top: window.top === window}))));
await E(() => { SYNQUENZER.setBpm(140); SYNQUENZER.setMetronome(false); SYNQUENZER.launchScene(0); SYNQUENZER.setKbMode('transpose'); });
await E(([seq, b0]) => new Promise(res => { let k = 0; const iv = setInterval(() => { const b = audBeat(); if (k < seq.length && b >= b0 + 4 * k + .05) { SYNQUENZER.keyOn(seq[k], .8, 'c' + k); const kk = k; setTimeout(() => SYNQUENZER.keyOff(0, 'c' + kk), 80); k++; } if (k >= seq.length) { clearInterval(iv); res(); } }, 2); }), [[57, 53, 48, 55, 57, 53, 48, 55], 4]);
await fr.waitForFunction(() => audBeat() >= 36.3, null, {polling: 5});
const box = await E(() => { const r = document.getElementById('bFang').getBoundingClientRect(); return [r.x + r.width / 2, r.y + r.height / 2, document.getElementById('bFang').textContent]; });
await pg.touchscreen.tap(box[0], box[1]); await sleep(150);
const fp = await E(() => SYNQUENZER.fangPart());
check('frame: FANG TEIL tap → 4-bar part', fp && fp.len === 4, fp && {len: fp.len, label: box[2]});
await E(() => SYNQUENZER.fangAccept('end')); await sleep(100);
check('frame: part + song mark', await E(() => SYNQUENZER.songMarks().length === 1 && !!SYNQUENZER.parts()[0]));
await E(() => { SYNQUENZER.stop(); }); await sleep(1300);
await E(() => { SYNQUENZER.songLoop(true); SYNQUENZER.songPlay(0); }); await sleep(3000);
check('frame: ▶ SONG plays', await E(() => SYNQUENZER.runtime().song.play));
const ex = await E(async () => { try { return await SYNQUENZER.exportProject(); } catch (e) { return 'ERR ' + e.message; } });
const mid = await E(async () => { try { return await SYNQUENZER.exportMidi('song'); } catch (e) { return 'ERR ' + e.message; } });
console.log('export project', ex, 'midi', mid);
await E(() => SYNQUENZER.stop());
check('frame: no Stimme-FANG, no 🎤', await E(() => SYNQUENZER.vsInfo().fangMode !== 'stimme' && SYNQUENZER.stimme().avail === false));
check('frame: no console errors', !errs.length, errs.slice(0, 5));
await br.close(); done();
