import {open, sleep, OUT} from './v3-qa-gmk2a-tl.mjs';
const T = await open(); const {p, E, errs} = T;
console.log('version', await E(() => SYNQUENZER.version), 'tracks', await E(() => (SYNQUENZER.project().project || SYNQUENZER.project()).tracks.map(t => t.name + ':' + (t.sound && t.sound.engine))));
console.log('api', await E(() => Object.keys(SYNQUENZER).filter(k => /mk|undo|redo|serial|load|save|scene|engine|sound|preset|clip/i.test(k)).join(',')));
await T.openEd(0);
const mkb = await T.rectText('button', /^MS ?2000$/); await T.tap(mkb.cx, mkb.cy, 800);
let pn = await T.panel(); console.log('panel', JSON.stringify({fmt: pn.fmt, half: pn.half, sel: pn.sel, knobs: pn.knobs && pn.knobs.map(k => k && k.l), matrix: pn.matrix}));
await T.tapMk('w1', 300); console.log('w1 list', JSON.stringify(await T.popTexts())); await T.tapPop(/^3 OSZ 1/); await sleep(200);
pn = await T.panel(); console.log('OSZ1', JSON.stringify({sel: pn.sel, knobs: pn.knobs.map(k => k && [k.l, k.v]), matrix: pn.matrix, lcd: await T.lcdTxt()}));
await T.tapMk('k0', 300); console.log('WELLE list', JSON.stringify(await T.popTexts())); await T.tapPop(/Speicherwelle/); await sleep(300);
pn = await T.panel(); console.log('after Speicherwelle', JSON.stringify({knobs: pn.knobs.map(k => k && [k.l, k.v]), lcd: await T.lcdTxt(), o1: (await T.pm(0)).t[0].o1}));
await T.tapMk('k2', 400); const wl = await T.popTexts(); console.log('wave list n', wl && wl.length, JSON.stringify(wl && wl.slice(0, 20)));
await p.screenshot({path: OUT + 'ex-wavelist.png'});
await T.closePop();
await T.tapMk('w2', 300); console.log('w2 list', JSON.stringify(await T.popTexts())); await T.tapPop(/^1 PATCH 1/); await sleep(200);
pn = await T.panel(); console.log('PATCH1', JSON.stringify({sel: pn.sel, knobs: pn.knobs.map(k => k && [k.l, k.v]), matrix: pn.matrix, lcd: await T.lcdTxt(), p: (await T.pm(0)).t[0].p}));
await T.tapMk('k0', 300); console.log('QUELLE list', JSON.stringify(await T.popTexts())); await T.closePop();
await T.tapMk('k1', 300); console.log('ZIEL list', JSON.stringify(await T.popTexts())); await T.closePop();
await p.screenshot({path: OUT + 'ex-patch.png'});
console.log('mkInfo', JSON.stringify(await E(() => SYNQUENZER.mkInfo())));
console.log('errs', JSON.stringify(errs));
await T.br.close();
