import {open, sleep, OUT} from './v3-qa-gmk4-tl.mjs';
const L = process.argv[2] === 'L';
const T = await open({viewport: L ? {width: 926, height: 428} : {width: 428, height: 926}}); const {p, E, errs} = T;
console.log('version', await E(() => SYNQUENZER.version && (typeof SYNQUENZER.version === 'function' ? SYNQUENZER.version() : SYNQUENZER.version)));
await T.openEd(0);
const mkb = await T.rectText('button', /^MS ?2000$/);
if (mkb) await T.tap(mkb.cx, mkb.cy, 800);
console.log('engine', await E(() => SYNQUENZER.getSound(0).engine), 'panel', JSON.stringify(await T.panel()));
await T.tapMk('w2', 400);
console.log('w2 list', JSON.stringify(await T.popTexts()));
await p.screenshot({path: OUT + 'ex-w2list-' + (L ? 'L' : 'P') + '.png'});
await T.tapPop(/MOD-FX/); await sleep(300);
console.log('panel after', JSON.stringify(await T.panel()), 'lcd', await T.lcd2());
await p.screenshot({path: OUT + 'ex-modfx-' + (L ? 'L' : 'P') + '.png'});
await T.tapMk('k0', 400); console.log('TYP list', JSON.stringify(await T.popTexts())); await T.closePop();
await T.w2(/DELAY/); console.log('lcd', await T.lcd2()); await p.screenshot({path: OUT + 'ex-delay-' + (L ? 'L' : 'P') + '.png'});
await T.tapMk('k0', 400); console.log('DLY TYP list', JSON.stringify(await T.popTexts())); await T.closePop();
await T.tapMk('k1', 400); console.log('SYNC list', JSON.stringify(await T.popTexts())); await T.tapPop(/^an$/); await sleep(200);
console.log('sync', JSON.stringify(await E(() => SYNQUENZER.mkGet(0).dly)), 'lcd', await T.lcd2());
await T.tapMk('k2', 400); console.log('NOTE list', JSON.stringify(await T.popTexts())); await p.screenshot({path: OUT + 'ex-notelist-' + (L ? 'L' : 'P') + '.png'}); await T.closePop();
await T.w2(/EQ/); console.log('lcd', await T.lcd2()); await p.screenshot({path: OUT + 'ex-eq-' + (L ? 'L' : 'P') + '.png'});
const knobsTxt = await E(() => [...document.querySelectorAll('.mkx[data-k^="k"]')].filter(e => e.getClientRects().length).map(e => e.dataset.k + ':' + e.textContent.replace(/\s+/g, ' ').trim()));
console.log('knobs', JSON.stringify(knobsTxt));
console.log('errs', JSON.stringify(errs));
await T.br.close();
