import {open, OUT, sleep, check, done} from './v3-qa-gp2a-lib.mjs';
import {fangRun} from './v3-qa-gp2a-parts.mjs';
const T = await open({mic: false}); const {p, E, errs} = T;
await E(() => { SYNQUENZER.setBpm(160); SYNQUENZER.setMetronome(false); });
const r1 = await fangRun(T, 1, ['Am', 'F', 'C', 'G']); console.log('fang1', JSON.stringify(r1));
const r2 = await fangRun(T, 2, ['F', 'G', 'Am', 'E']); console.log('fang2', JSON.stringify(r2));
await E(() => SYNQUENZER.stop()); await sleep(300);
console.log('keys', JSON.stringify(await E(() => [...document.querySelectorAll('#partBar .pk')].map(k => k.textContent))));
console.log('parts', JSON.stringify(await E(() => SYNQUENZER.parts().filter(Boolean).map(x => ({name: x.name, len: x.len, ch: x.chords && x.chords.ch.map(c => c.b + ':' + (c.tg && c.tg.name))})))));
await T.shot('x3-clipview');
// drag STROPHE onto SONG ⇄
const k0 = await T.rect('#partBar .pk'); const cn = await T.rect('.corner.sw');
console.log('key', JSON.stringify(k0), 'corner', JSON.stringify(cn));
await T.down(k0.cx, k0.cy); await sleep(480);
console.log('ghost', await E(() => !!document.querySelector('.drg-ghost')), 'corner txt', await E(() => document.querySelector('.corner.sw').textContent));
await T.shot('x3-lifted');
await T.glide(k0.cx, k0.cy, cn.cx, cn.cy, 8, 16);
console.log('songOn', await T.songOn());
let inf = await T.info();
await T.glide(cn.cx, cn.cy, inf.canvas.x + 0 * 36 + 4, inf.canvas.y + 80, 10, 16);
console.log('drag', JSON.stringify((await T.info()).drag));
await T.shot('x3-dragging');
await T.up(); await sleep(500);
console.log('pop after drop', await T.pop());
console.log('song', JSON.stringify(await E(() => { const s = SYNQUENZER.song(); return s && {bars: s.bars, marks: s.marks, lanes: s.lanes}; })));
console.log('undo', JSON.stringify(await T.undoTop()));
await T.shot('x3-dropped');
console.log('errs', errs);
await T.br.close();
