// T17: ● REC aus dem Stand (Einzähler), Weg je Argument; gesungen 2 Takte ab Schlag 0; Tipp ● bei Schlag 7,7
import {open, sleep, voice, playAtBeat, waitBeat, result, calib} from './v3-qa-vs2acc-h.mjs';
const route = process.argv[2] || 'wired';
let fail = 0; const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) fail++; };
const H = await open({vp: 'P1'}), p = H.p;
await p.evaluate(() => { const T = []; window.__toasts = T; const el = document.getElementById('toast'); new MutationObserver(() => T.push(el.textContent)).observe(el, {childList: true, subtree: true, characterData: true}); });
if (route === 'wired') await p.evaluate(() => { window.__q.label = 'Headset Microphone'; });
await p.tap('#segMic');
await p.waitForFunction(() => window.__q.bus, null, {timeout: 5000});
if (route === 'speaker') await p.evaluate(() => window.__q.loop(-30, 40));
await p.waitForFunction(() => { const s = SYNQUENZER.stimme(); return s.phase === 'live' && (s.lastCal || s.route !== 'speaker'); }, null, {timeout: 20000});
if (route === 'wired') await calib(p);
await p.evaluate(() => { SYNQUENZER.stimmeSheet(false); SYNQUENZER.stopAllClips && SYNQUENZER.stopAllClips(); SYNQUENZER.stop(); SYNQUENZER.selectSlot(0, 3); });
await sleep(300);
await p.tap('#bRec'); await sleep(30);
const ck = await p.evaluate(() => ({c: SYNQUENZER.vsClock(), rec: SYNQUENZER.runtime().rec}));
console.log('  start', JSON.stringify(ck.rec), 'countIn-Start', ck.c.start - ck.c.now);
const SB = ck.c.spb;
const MEL = [[0, 1, 64], [1, 1, 62], [2, 2, 60], [4, 1, 62], [5, 1, 64], [6, 1.5, 64]];
await playAtBeat(p, voice(MEL.map(([b, d, m]) => ({on: 0.05 + b * SB, dur: d * SB, m})), {fs: 16000, seed: 4}), 0, 0.05, 16000);
await waitBeat(p, 7.7); await p.tap('#bRec');
await p.waitForFunction(() => SYNQUENZER.runtime().rec.state === 'off', null, {timeout: 20000});
await p.waitForFunction(() => SYNQUENZER.vsResult() || (!SYNQUENZER.vsInfo().busy && SYNQUENZER.vsInfo().runs > 0), null, {timeout: 20000}).catch(() => {});
const r = await result(p);
console.log('  Ergebnis', JSON.stringify(r && {scene: r.scene, len: r.len, start: r.start, notes: r.notes.map(n => [n.t, n.n])}));
const hit = r ? MEL.filter(([b, , m]) => r.notes.some(n => n.n === m && Math.abs(n.t - b) <= 0.13)).length : 0;
ok(r && r.scene === 3, 'MELODIE Szene 4');
ok(hit >= 6 && r.notes.length === MEL.length, `Noten ${hit}/${MEL.length}, erkannt ${r && r.notes.length}`);
console.log('  Toasts', JSON.stringify(await p.evaluate(() => window.__toasts.filter((x, i, a) => x && a.indexOf(x) === i))));
ok(!H.errs.length, 'keine Konsolenfehler ' + JSON.stringify(H.errs.slice(0, 3)));
await H.br.close();
console.log(fail ? 'FAIL ' + fail : 'ALLE OK');
