import {chromium} from 'playwright';
const EXE = '/opt/pw-browsers/chromium-1243/chrome-linux64/chrome';
const file = process.argv[2];
const sleep = ms => new Promise(r => setTimeout(r, ms));
const br = await chromium.launch({executablePath: EXE, args: ['--autoplay-policy=no-user-gesture-required']});
const ctx = await br.newContext({viewport: {width: 428, height: 926}, hasTouch: true, isMobile: true, deviceScaleFactor: 1});
const p = await ctx.newPage(); const errs = [];
p.on('pageerror', e => errs.push(String(e)));
await p.goto('file://' + file);
await p.waitForFunction(() => window.SYNQUENZER && window.SYNQUENZER.version, null, {timeout: 20000});
await sleep(800);
const E = (f, a) => p.evaluate(f, a);
const st = () => E(() => { const s = document.getElementById('synthSheet'); return {editor: !!SYNQUENZER.runtime().editor, cls: s && s.className, disp: s && getComputedStyle(s).display}; });
await E(() => { SYNQUENZER.selectTrack(0); SYNQUENZER.openEditor(); }); await sleep(600);
console.log('header buttons', JSON.stringify(await E(() => [...document.querySelectorAll('#synthSheet button')].filter(b => b.getClientRects().length).slice(0, 14).map(b => b.textContent.trim().slice(0, 10)))));
await E(() => SYNQUENZER.closeEditor()); await sleep(500);
console.log('setEngine', await E(() => typeof SYNQUENZER.setEngine));
await E(() => { SYNQUENZER.setEngine(0, 'mk'); SYNQUENZER.selectTrack(0); SYNQUENZER.openEditor(); }); await sleep(800);
console.log('MK open', JSON.stringify(await st()));
const x = await E(() => { const e = [...document.querySelectorAll('button')].filter(b => b.getClientRects().length && b.textContent.trim() === '✕')[0]; const r = e.getBoundingClientRect(); return {x: r.x + r.width / 2, y: r.y + r.height / 2}; });
await p.touchscreen.tap(x.x, x.y); await sleep(1000);
console.log('MK after ✕', JSON.stringify(await st()));
await E(() => SYNQUENZER.closeEditor()); await sleep(800);
console.log('MK after closeEditor', JSON.stringify(await st()));
console.log('errs', errs.slice(0, 3));
await br.close();
