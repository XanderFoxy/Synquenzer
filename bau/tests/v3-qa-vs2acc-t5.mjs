// T5: ● REC mit 🎤 über die Oberfläche (Tipp ●, singen, Tipp ●): MELODIE-Clip in derselben Szene, ein Undo; belegter Platz: Noten
// kommen dazu, ein Undo stellt den alten Clip her; kein „Nichts aufgenommen“; hörbar.
import {open, sleep, voice, playAtBeat, waitBeat, result, calib} from './v3-qa-vs2acc-h.mjs';
let fail = 0; const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) fail++; };
const pre = process.argv[2] === 'pre';
const H = await open({vp: 'P1'}), p = H.p;
await p.evaluate(() => { window.__q.label = 'Headset Microphone'; const T = []; window.__toasts = T; const el = document.getElementById('toast'); new MutationObserver(() => T.push(el.textContent)).observe(el, {childList: true, subtree: true, characterData: true}); });
await p.tap('#segMic');
await p.waitForFunction(() => SYNQUENZER.stimme().phase === 'live' && SYNQUENZER.vsClock().ring && SYNQUENZER.vsClock().ring.end > 0, null, {timeout: 8000});
await sleep(700); await calib(p);
await p.evaluate(() => SYNQUENZER.stimmeSheet(false));
const OLD = {len: 2, key: {root: 0, scale: 'ionian', src: 'auto'}, notes: [{t: 0, d: 0.5, n: 72, v: 0.8}, {t: 4, d: 0.5, n: 74, v: 0.8}]};
if (pre) await p.evaluate(c => SYNQUENZER.setClip(5, 2, c), OLD);
await p.evaluate(() => SYNQUENZER.selectSlot(0, 2)); await sleep(100);
await p.tap('#bPlay'); await sleep(50);
const SB = await p.evaluate(() => SYNQUENZER.vsClock().spb);
const u0 = await p.evaluate(() => SYNQUENZER.undoInfo().n);
await waitBeat(p, 6); await p.tap('#bRec');
const rs = await p.evaluate(() => SYNQUENZER.runtime().rec);
console.log('  REC', JSON.stringify(rs));
const MEL = [[8, 1, 62], [9, 1, 64], [10, 2, 65], [12, 1, 64], [13, 1, 62], [14, 1.5, 60]];
const LEAD = 0.05;
await playAtBeat(p, voice(MEL.map(([b, d, m]) => ({on: LEAD + (b - 8) * SB, dur: d * SB, m})), {seed: 11}), 8, LEAD);
await waitBeat(p, 16.3); await p.tap('#bRec');
const ends = await p.evaluate(() => SYNQUENZER.runtime().rec);
console.log('  nach 2. Tipp', JSON.stringify(ends));
await p.waitForFunction(() => SYNQUENZER.runtime().rec.state === 'off', null, {timeout: 20000});
const offAt = await p.evaluate(() => { const c = SYNQUENZER.vsClock(); return (c.now - c.outLat - c.start) / c.spb; });
await p.waitForFunction(() => SYNQUENZER.vsResult() || (!SYNQUENZER.vsInfo().busy && SYNQUENZER.vsInfo().runs > 0), null, {timeout: 20000}).catch(() => {});
const r = await result(p);
const resAt = await p.evaluate(() => { const c = SYNQUENZER.vsClock(); return (c.now - c.outLat - c.start) / c.spb; });
console.log('  REC aus bei Schlag', offAt.toFixed(2), 'Ergebnis bei', resAt.toFixed(2), 'runs', await p.evaluate(() => SYNQUENZER.vsInfo().runs));
console.log('  Ergebnis', JSON.stringify(r && {kind: r.kind, scene: r.scene, len: r.len, start: r.start, notes: r.notes.map(n => [n.t, n.n])}));
ok(r && r.kind === 'rec' && r.track === 5 && r.scene === 2, `MELODIE in derselben Szene 3: ${r && r.scene + 1}`);
const want = MEL.map(([b, , m]) => ({o: b - 8, m}));
const hit = r ? want.filter(w => r.notes.some(n => n.n === w.m && Math.abs(n.t - w.o) <= 0.13)).length : 0;
ok(hit >= 5, `Noten ${hit}/${MEL.length}`);
if (pre) ok(r && OLD.notes.every(o => r.notes.some(n => n.n === o.n && Math.abs(n.t - o.t) < 1e-6)) && r.len === 2, 'belegter Platz: alte Noten bleiben, Länge bleibt 2 Takte');
const ui = await p.evaluate(() => SYNQUENZER.undoInfo());
ok(ui.n === u0 + 1 && ui.top.label === 'Stimme', `ein Undo-Schritt (${u0} → ${ui.n}, „${ui.top && ui.top.label}“)`);
const ts = await p.evaluate(() => window.__toasts.filter((x, i, a) => x && a.indexOf(x) === i));
ok(!ts.some(x => /Nichts aufgenommen/.test(x)), 'kein „Nichts aufgenommen“ (' + JSON.stringify(ts) + ')');
ok(await p.evaluate(() => SYNQUENZER.getClip(0, 2)) === null, 'Synth 1 Szene 3 bleibt leer');
await p.evaluate(() => SYNQUENZER.clearLog()); const b0 = await p.evaluate(() => { const c = SYNQUENZER.vsClock(); return (c.now - c.outLat - c.start) / c.spb; });
await waitBeat(p, b0 + 12);
const lg = await p.evaluate(() => SYNQUENZER.noteLog(4096).filter(e => e.track === 5).map(e => [e.beat, e.out]));
ok(lg.length >= 3, 'MELODIE klingt nach der Aufnahme: ' + JSON.stringify(lg.slice(0, 8)));
if (await p.evaluate(() => !!document.querySelector('.pop.vsres'))) await p.tap('.pop.vsres [data-a="ok"]');
await sleep(150); await p.tap('#bUndo'); await sleep(250);
const after = await p.evaluate(() => SYNQUENZER.getClip(5, 2));
ok(pre ? JSON.stringify(after.notes.map(n => [n.t, n.n])) === JSON.stringify(OLD.notes.map(n => [n.t, n.n])) && after.len === 2 : after === null, 'ein ↶ stellt den Zustand vorher her: ' + JSON.stringify(after && after.notes.map(n => [n.t, n.n])));
ok(!H.errs.length, 'keine Konsolenfehler ' + JSON.stringify(H.errs.slice(0, 3)));
await H.br.close();
console.log(fail ? 'FAIL ' + fail : 'ALLE OK');
