// Independent check: pull of newer server version locks; user taps "Neu laden" and the reload directly serves "4.9.0".
import fs from 'fs';
import {setup, go, boot, idb, server, X, newerFile, ok, finish, UID} from './v3-mk0qa/h.mjs';
const APP = process.argv[2], EMU = process.argv[3];
const srv = server();
const tmp = await setup(server(), {file: APP}); await go(tmp.page); const baseTxt = await tmp.page.evaluate(() => SYNQUENZER.serialize()); await tmp.ctx.close();
const mine = JSON.parse(baseTxt); mine.project.id = 'p-pull-b'; mine.project.name = 'Pull-B';
const NEW = newerFile(baseTxt, p => { p.id = 'p-pull-b'; p.name = 'Pull-B'; p.tracks[1].sound = X; p.bpm = 133; });
srv.projects.set('sid-b', {row: {id: 'sid-b', owner_id: UID, local_id: 'p-pull-b', title: 'Pull-B', version: 2, format: 5, app_code: 4009000, updated_at: new Date().toISOString(), updated_by: UID, deleted_at: null, space_id: null}, body: NEW});
const {ctx, page, errs, st} = await setup(srv, {file: APP});
await go(page);
await page.evaluate(t => SYNQUENZER.importJSON(t), JSON.stringify(mine)); await page.waitForTimeout(500);
await page.evaluate(() => SYNQUENZER.save());
await page.evaluate(async uid => { await metaSet('p-pull-b', {uid, sid: 'sid-b', base: 1, space: null, dirty: false, sum: '', mt: Date.now()}); }, UID);
await page.evaluate(uid => localStorage.setItem('synq-auth', JSON.stringify({user: {id: uid}, expires_at: 9999999999, access_token: 'tok'})), UID);
await page.reload(); await boot(page);
await page.waitForFunction(() => SYNQUENZER.cloud().state === 'online', null, {timeout: 15000}).catch(() => {});
await page.waitForFunction(() => SYNQUENZER.nvState().lock, null, {timeout: 8000}).catch(() => {});
await page.waitForTimeout(1500);
const a = await page.evaluate(async () => ({lock: !!SYNQUENZER.nvState().lock, ban: !!document.getElementById('nvBan'), bpm: S.bpm, e1: SYNQUENZER.getSound(1).engine, m: await metaGet('p-pull-b')}));
const kva = await idb(page, 'get', 'project');
console.log('after pull on 4.8.1:', JSON.stringify(a), 'KV bpm', kva.project.bpm, 'KV e1', kva.project.tracks[1].sound && kva.project.tracks[1].sound.engine);
// "Neu laden" -> server now serves 4.9.0
st.html = fs.readFileSync(EMU);
await page.reload(); await boot(page);
await page.waitForFunction(() => SYNQUENZER.cloud().state === 'online', null, {timeout: 15000}).catch(() => {});
await page.waitForTimeout(2500);
const b = await page.evaluate(async () => ({v: SYNQUENZER.version, bpm: S.bpm, e1: SYNQUENZER.getSound(1).engine, m: await metaGet('p-pull-b'), pulls: SYNQUENZER.cloud().pulled}));
console.log('after reload to 4.9.0:', JSON.stringify(b));
ok('4.9.0 shows newest server state', b.e1 === 'xyz' && b.bpm === 133, JSON.stringify({bpm: b.bpm, e1: b.e1}));
const n0 = srv.calls.filter(c => c.fn === 'save_project').length;
await page.evaluate(() => { S.tracks[0].mute = !S.tracks[0].mute; markDirty(); });
await page.waitForTimeout(1500); await page.evaluate(() => SYNQUENZER.save()); await page.evaluate(() => SYNQUENZER.cloudSync()); await page.waitForTimeout(2500);
const sp = srv.calls.filter(c => c.fn === 'save_project').slice(n0);
const body = srv.projects.get('sid-b').body, bb = typeof body === 'string' ? JSON.parse(body) : body;
console.log('save_project:', sp.map(c => c.body.p_app + '/' + c.body.p_format + '/base ' + c.body.p_base + ' -> ' + (c.res && c.res.status)).join(' | '));
ok('server keeps newer state after first edit on 4.9.0', bb.project.tracks[1].sound.engine === 'xyz' && bb.project.bpm === 133, 'server v' + srv.projects.get('sid-b').row.version + ' e1=' + bb.project.tracks[1].sound.engine + ' bpm=' + bb.project.bpm);
console.log('errors:', errs.join(' | ').slice(0, 300));
await ctx.close(); await finish();
