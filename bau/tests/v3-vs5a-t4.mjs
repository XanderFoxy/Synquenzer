// VS5a T4 (FP-IPHONE / FP-DSP): 60-s take – detection and render in the worker, long tasks on the main thread, memory
import {launch, open5, sleep, toI16, SR} from './v3-vs5a-h.mjs';
import {song} from '../vs-dsp/test-signals.mjs';
let fail = 0; const ok = (c, m) => { console.log((c ? '✓ ' : '✗ ') + m); if (!c) fail++; };
const br = await launch(null);
const H = await open5(br, {viewport: {width: 390, height: 844}, touch: true}), p = H.p;
await p.evaluate(() => { SYNQUENZER.newProject(); SYNQUENZER.setBpm(100); window.__lt = []; new PerformanceObserver(l => { for (const e of l.getEntries()) window.__lt.push([Math.round(e.startTime), Math.round(e.duration)]); }).observe({entryTypes: ['longtask']}); });
const S1 = song(SR, 60, {seed: 6});
const r = await p.evaluate(pcm => SYNQUENZER.tkInject({pcm, sr: 48000, scene: 0, len: 16}), toI16(S1.x));
await p.evaluate(() => { window.__lt = []; });
const mk = n => p.evaluate(n => { (window.__ph = window.__ph || []).push([n, Math.round(performance.now())]); }, n);
await mk('detect');
const t0 = Date.now(); const det = await p.evaluate(id => SYNQUENZER.wpDetect(id), r.id); const dt = Date.now() - t0;
const I = await p.evaluate(id => SYNQUENZER.wpInfo(id), r.id);
const hit = S1.onsets.filter(t => det.some(m => Math.abs(m.t - t) < 0.03)).length;
console.log('detect 60 s:', dt, 'ms', JSON.stringify(I.lastDet), 'marks', det.length, 'onsets hit', hit + '/' + S1.onsets.length);
ok(I.lastDet.how === 'worker', 'detection runs in the worker (' + I.lastDet.ms + ' ms for 60 s)');
ok(hit / S1.onsets.length >= 0.9, 'sung test song: ≥ 90 % of onsets within ±30 ms (' + hit + '/' + S1.onsets.length + ')');
await mk('open');
await p.evaluate(r => { SYNQUENZER.selectSlot(r.track, 0); SYNQUENZER.wpOpen({t: r.track, s: 0}); }, r); await sleep(500);
await mk('quant');
await p.evaluate(r => SYNQUENZER.wpQuantize({t: r.track, s: 0}, {grid: '1/16', strength: 1}), r);
await p.evaluate(id => SYNQUENZER.wpPlayed(id, 0, 4), r.id);
const I2 = await p.evaluate(id => SYNQUENZER.wpInfo(id), r.id);
console.log('render', JSON.stringify(I2.last), 'grid', I2.warp && I2.warp.res);
ok(I2.last && I2.last.how === 'worker', 'render in the worker (' + (I2.last && I2.last.ms) + ' ms)');
await mk('slider');
await p.evaluate(async () => { const i = document.querySelector('#wpSheet .qrow input'); for (let v = 100; v >= 40; v -= 3) { i.value = v; i.dispatchEvent(new Event('input')); await new Promise(r => setTimeout(r, 30)); } i.dispatchEvent(new Event('change')); });
await sleep(1500);
await mk('zoom');
await p.evaluate(() => document.body.click()); await sleep(500); await p.evaluate(() => { window.__lt = []; });
console.log('zoom ms', JSON.stringify(await p.evaluate(async () => { const o = []; for (let k = 0; k < 4; k++) { const t = performance.now(); document.querySelector('#wpSheet .wpz').click(); o.push([document.querySelector('#wpSheet .wpz').textContent, Math.round(performance.now() - t)]); await new Promise(r => setTimeout(r, 50)); } return o; })));
const lt = await p.evaluate(() => window.__lt);
console.log('long tasks', JSON.stringify(lt), 'phases', JSON.stringify(await p.evaluate(() => window.__ph)));
ok(!lt.some(([s, d]) => d > 50), 'no long task > 50 ms on the main thread during detect / quantize / slider / zoom');
const mem = await p.evaluate(() => performance.memory ? Math.round(performance.memory.usedJSHeapSize / 1e6) : null);
console.log('heap MB', mem);
ok(!H.errs.length, 'no console errors ' + JSON.stringify(H.errs));
await br.close();
console.log(fail ? 'FAIL ' + fail : 'ALL OK');
