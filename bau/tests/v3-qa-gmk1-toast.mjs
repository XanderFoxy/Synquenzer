import {open, sleep, OUT} from './v3-qa-gmk1-tl.mjs';
import {setupProject} from './v3-qa-gmk1-setup.mjs';
const file = process.argv[2];
const T = await open(file ? {file} : {}); const {p, E, errs} = T;
await setupProject(E);
await E(() => { SYNQUENZER.selectTrack(0); SYNQUENZER.openEditor(); }); await sleep(500);
await E(() => SYNQUENZER.initSound(0)); await sleep(300);
await T.tapTxt('.hb.ur', /^↶$/, 300);
const tr = await E(() => { const t = document.getElementById('toast'); const r = t.getBoundingClientRect(); return {txt: t.textContent, x: r.x, y: r.y, w: r.width, h: r.height, btns: [...t.querySelectorAll('button')].map(b => { const q = b.getBoundingClientRect(); return [b.textContent, Math.round(q.x), Math.round(q.y), Math.round(q.width), Math.round(q.height)]; })}; });
console.log('toast in editor', JSON.stringify(tr));
const x = await T.rectText('button', /^✕$/); console.log('✕ at', JSON.stringify(x));
const hitX = await E(([x, y]) => { const e = document.elementFromPoint(x, y); return e.tagName + '.' + e.className + ' ' + e.textContent.trim().slice(0, 20); }, [x.cx, x.cy]);
console.log('element at ✕', hitX);
await T.tap(x.cx, x.cy, 300);
console.log('after ✕: editor', await E(() => SYNQUENZER.runtime().editor), 'name', await E(() => SYNQUENZER.getSound(0).name));
const tr2 = await E(() => { const t = document.getElementById('toast'); const r = t.getBoundingClientRect(); return {vis: !!t.offsetWidth, txt: t.textContent, x: r.x, y: r.y, w: r.width, h: r.height, btns: [...t.querySelectorAll('button')].map(b => { const q = b.getBoundingClientRect(); return [b.textContent, Math.round(q.x), Math.round(q.y), Math.round(q.width), Math.round(q.height)]; })}; });
console.log('toast after close', JSON.stringify(tr2));
const s4 = await T.rectText('button.scn', /^▶\s*4/); console.log('▶4 at', JSON.stringify(s4));
const hit4 = await E(([x, y]) => { const e = document.elementFromPoint(x, y); return e.tagName + '.' + e.className + ' ' + e.textContent.trim().slice(0, 20); }, [s4.cx, s4.cy]);
console.log('element at ▶4', hit4);
await p.screenshot({path: OUT + 'toast.png'});
await T.tap(s4.cx, s4.cy, 300);
console.log('after ▶4 tap: name', await E(() => SYNQUENZER.getSound(0).name), 'queued', JSON.stringify(await E(() => SYNQUENZER.runtime().queued)));
await T.br.close();
