// QA VC2a: a FANG-chip drop into the song is ONE gesture / ONE undo step (group) -> how many data events does the recorder make?
import { open, T, sleep } from './n5-h-qa-lib.mjs';
import { SETUP55 } from './v3-qa-v2e2-lib.mjs';
const {b, p, errs, cdp} = await open('P1');
const t = T(p, cdp), E = t.E;
await E(SETUP55(false)); await E(() => window.SYNQUENZER.songView(false)); await sleep(2600);
await E(() => historyCheck());
await E(() => { const Q = window.SYNQUENZER; Q.setBpm(240); Q.setMetronome && Q.setMetronome(false); Q.launchClip(4, 0); Q.launchClip(0, 0); Q.launchClip(1, 1); return 1; });
await p.waitForFunction(() => window.SYNQUENZER.runtime().playing, null, {timeout: 5000});
await p.waitForFunction(() => window.SYNQUENZER.runtime().beat >= 8.2, null, {timeout: 20000, polling: 5});
await E(() => window.SYNQUENZER.fangTeil({beat: window.SYNQUENZER.runtime().beat}));
await sleep(300);
await t.drain(); await sleep(50);
const n0 = await t.evN(); const u0 = await E(() => UNDO.length);
const chip = await t.rect('.fsheet .fs-chip');
console.log('chip', JSON.stringify(chip));
await t.down(chip.cx, chip.cy); await sleep(1150);
const inf = await t.info();
await t.glide(chip.cx, chip.cy, inf.canvas.x + 7 * 36 + 4 - inf.x0, inf.canvas.y + 100, 10, 16);
await t.up(); await sleep(500);
await t.drain(); await sleep(50);
const u1 = await E(() => ({n: UNDO.length, top: UNDO[UNDO.length - 1] && {kind: UNDO[UNDO.length - 1].kind, label: UNDO[UNDO.length - 1].label, items: (UNDO[UNDO.length - 1].items || []).map(x => x.kind)}}));
const evs = await t.evSince(n0);
const data = evs.filter(e => e.u !== 'ctx');
console.log('undo before', u0, 'after', JSON.stringify(u1));
console.log('events after drop:', evs.length, 'data:', data.length);
for (const e of evs) console.log('  ', e.u, JSON.stringify(e.z), e.l, 'ops', (e.d || []).length, (e.d || []).slice(0, 3).map(o => o.op + ' ' + o.path).join(' | '));
const RES = {undoSteps: u1.n - u0, dataEvents: data.length};
console.log('RESULT', JSON.stringify(RES), RES.undoSteps === 1 && RES.dataEvents === 1 ? 'OK' : 'DEFECT: one gesture/one undo step but ' + data.length + ' data events');
console.log('historyCheck', JSON.stringify(await E(() => historyCheck({detail: true}))));
console.log('errors', JSON.stringify(errs));
await b.close();
